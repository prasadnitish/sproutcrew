import { readFileSync, writeFileSync } from 'node:fs';
// Writes src/tokens.css from src/brand/tokens.json. Electric is plain :root; each other scheme follows it with the
// cascade in DESIGN_SPEC.md §3.1: light, then dark for Match this Mac, then dark for an explicit Dark.
const root = new URL('../', import.meta.url);
const tokens = JSON.parse(readFileSync(new URL('src/brand/tokens.json', root), 'utf8'));
const declarations = (values, prefix = '', indent = '  ') => Object.entries(values).map(([key, value]) =>
  typeof value === 'object' ? declarations(value, `${prefix}${key}-`, indent) : `${indent}--${prefix}${key}: ${value};`
).join('\n');
const dark = declarations(tokens.semantic.dark);
const schemes = Object.entries(tokens.schemes).map(([id, { light, dark: d }]) => {
  const q = `:root[data-scheme="${id}"]`;
  const body = declarations(d, '', '    ');
  return `${q} {\n${declarations(light)}\n  color-scheme: light;\n}\n@media (prefers-color-scheme: dark) {\n  ${q}:not([data-theme="light"]) {\n${body}\n    color-scheme: dark;\n  }\n}\n${q}[data-theme="dark"] {\n${declarations(d)}\n  color-scheme: dark;\n}\n`;
}).join('\n');
const css = `/* Generated by scripts/build-tokens.mjs. Edit src/brand/tokens.json. */\n:root {\n${declarations(tokens.primitive, 'sc-')}\n${declarations(tokens.semantic.light)}\n${declarations(tokens.component)}\n  color-scheme: light;\n}\n\n@media (prefers-color-scheme: dark) {\n  :root:not([data-theme="light"]) {\n${declarations(tokens.semantic.dark, '', '    ')}\n    color-scheme: dark;\n  }\n}\n:root[data-theme="dark"] {\n${dark}\n  color-scheme: dark;\n}\n\n/* Schemes (DESIGN_SPEC.md §3.2). */\n${schemes}`;
const destination = new URL('src/tokens.css', root);
if (process.argv.includes('--check')) {
  if (readFileSync(destination, 'utf8') !== css) throw new Error('tokens.css is out of date. Run npm run tokens:build.');
  console.log('Design tokens are in sync.');
} else { writeFileSync(destination, css); console.log('Generated src/tokens.css'); }
